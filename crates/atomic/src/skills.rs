/// Facts generated from the definitions, appended to a field's note.
fn field_facts(field: &str, defs: &Definitions<'_>, member: &Member) -> Result<String, String> {
    let quoted = |values: &[&str]| {
        values
            .iter()
            .map(|v| format!("`{v}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    Ok(match field {
        "atomic" => format!(" The only version is `{}`.", defs.format_version),
        "kind" => {
            let declared = literal_union(&member.ty)?;
            let refused: Vec<&str> = declared
                .iter()
                .map(String::as_str)
                .filter(|value| !defs.kinds.contains(value))
                .collect();
            let mut facts = format!(" This version runs {}.", quoted(defs.kinds));
            if !refused.is_empty() {
                let _ = write!(
                    facts,
                    " The type also allows {}, which `atomic check` refuses.",
                    quoted(&refused)
                );
            }
            facts
        }
        "model" => format!(" Tiers: {}.", quoted(defs.model_tiers)),
        _ => String::new(),
    })
}

/// The string literals of a union type such as `'a' | 'b'`.
fn literal_union(ty: &str) -> Result<Vec<String>, String> {
    ty.split('|')
        .map(|part| {
            part.trim()
                .strip_prefix('\'')
                .and_then(|p| p.strip_suffix('\''))
                .map(str::to_owned)
                .ok_or_else(|| format!("expected a union of string literals, not `{ty}`"))
        })
        .collect()
}

/// The configuration field reference.
pub fn fields_reference(defs: &Definitions<'_>) -> Result<String, String> {
    let members = config_members(defs.declarations)?;
    let member = |name: &str| members.iter().find(|m| m.name == name);
    for (field, _) in FIELD_NOTES {
        if !defs.fields.contains(field) {
            return Err(format!(
                "a note describes `{field}`, which the loader does not read"
            ));
        }
    }
    for m in &members {
        if !defs.fields.contains(&m.name.as_str()) && !defs.later.contains(&m.name.as_str()) {
            return Err(format!(
                "AtomConfig declares `{}`, which the loader neither reads nor refuses",
                m.name
            ));
        }
    }
    let mut out = String::new();
    let _ = writeln!(out, "{GENERATED}\n");
    out.push_str(
        "# Atom configuration fields\n\n\
         The frontmatter of an `.atom.astro` file exports one literal object:\n\n\
         ```astro\n\
         ---\n\
         import type { Props, Input, Output } from '../.atomic/types/<atom-name>';\n\
         import type { AtomConfig } from '../.atomic/types/authoring';\n\
         const { input }: Props = Astro.props;\n\
         export const config: AtomConfig<Input, Output> = {\n  description: '…',\n};\n\
         ---\n\
         ```\n\n\
         The import paths are relative from the atom file to `.atomic/types/` in the \
         project root; `atomic check` writes those declarations. Values are literals: no \
         variables, calls or spreads. Only `validate` holds functions.\n\n",
    );
    out.push_str("## Project layout\n\n");
    let _ = write!(
        out,
        "A project is the directory holding `atomic.yaml` (a repository of agents) or \
         `.atomic/atomic.yaml` (atomic embedded in another repository). The smallest \
         manifest is:\n\n```yaml\natomic: {}\nname: <project-name>\n```\n\n\
         Paths are relative to the manifest's directory. atomic finds files by these \
         default globs:\n\n",
        defs.format_version
    );
    for (collection, globs) in defs.collections {
        let _ = writeln!(
            out,
            "- {collection}: {}",
            globs
                .iter()
                .map(|g| format!("`{g}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    out.push_str(
        "\nAn atom's schemas default to sidecars named after its file: for \
         `atoms/<stem>.atom.astro`, `atoms/<stem>.input.schema.yaml` and \
         `atoms/<stem>.output.schema.yaml` (`.json` also works; both forms of one sidecar \
         is an error). Eval cases for atom `<name>` go in `evals/<name>/`, one case per \
         `.yaml` file or one per line of a `.jsonl` file. `.atomic/types/` is generated: \
         never edit it, and keep it out of version control.\n\n",
    );
    out.push_str("## Fields\n\nEvery field is optional.\n\n");
    for field in defs.fields {
        let note = FIELD_NOTES
            .iter()
            .find(|(name, _)| name == field)
            .map(|(_, note)| *note)
            .ok_or_else(|| format!("the loader reads `{field}`, but no note describes it"))?;
        let m = member(field).ok_or_else(|| {
            format!("the loader reads `{field}`, but AtomConfig does not declare it")
        })?;
        let _ = write!(out, "- **`{field}`** (`{}`): {note}", m.ty);
        out.push_str(&field_facts(field, defs, m)?);
        if let Some(doc) = &m.doc {
            let _ = write!(out, " {doc}");
        }
        out.push('\n');
    }
    out.push_str(
        "\nIn the types, `I`, `O`, `C` and `R` are the generated `Input`, `Output`, case and \
         context types.\n\n## Refused by this version\n\n\
         `atomic check` fails on these fields, saying they are not supported yet: ",
    );
    out.push_str(
        &defs
            .later
            .iter()
            .map(|f| format!("`{f}`"))
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str(". Any other field name fails as unknown.\n");
    Ok(out)
}

/// A prompt construct with a body that compiles.
#[derive(Clone, Copy, Debug)]
pub struct Construct {
    /// What it is for.
    pub title: &'static str,
    /// One line of explanation.
    pub note: &'static str,
    /// Lines added to the frontmatter after the standard imports and the
    /// `Props` binding.
    pub frontmatter: &'static str,
    /// Configuration object literal.
    pub config: &'static str,
    /// The prompt body.
    pub body: &'static str,
    /// A local component the body imports, as `(file name, source)`.
    pub component: Option<(&'static str, &'static str)>,
}

impl Construct {
    const fn body(title: &'static str, note: &'static str, body: &'static str) -> Self {
        Self {
            title,
            note,
            frontmatter: "",
            config: "{}",
            body,
            component: None,
        }
    }
}

