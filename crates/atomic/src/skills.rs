/// The prompt syntax reference.
pub fn prompt_reference() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{GENERATED}\n");
    out.push_str(
        "# Prompt syntax\n\n\
         The body of an `.atom.astro` file is the prompt. atomic parses it with the Astro \
         parser and interprets a small, TypeScript-shaped subset; it never runs it as \
         JavaScript. Only the TypeScript helpers an atom imports run, in an isolated \
         runtime. Whitespace is prompt text. Examples show only the frontmatter lines \
         they add to the standard imports and `Props` binding in fields.md. Every \
         example below compiles with \
         `atomic check`, against an input with `text` (string), `items` (string list), \
         `urgent` (boolean) and an optional `extra.note` (string), and an output with \
         `summary` (string) and `labels` (string list).\n\n",
    );
    for c in CONSTRUCTS {
        let _ = writeln!(out, "## {}\n\n{}\n", c.title, c.note);
        out.push_str("```astro\n");
        if !c.frontmatter.is_empty() || c.config != "{}" {
            out.push_str("---\n");
            if !c.frontmatter.is_empty() {
                let _ = writeln!(out, "{}", c.frontmatter);
            }
            if c.config != "{}" {
                let _ = writeln!(
                    out,
                    "export const config: AtomConfig<Input, Output> = {};",
                    c.config
                );
            }
            out.push_str("---\n");
        }
        let _ = writeln!(out, "{}\n```\n", c.body);
        if let Some((file, source)) = c.component {
            let fence = if file.ends_with(".ts") { "ts" } else { "astro" };
            let _ = writeln!(out, "`{file}`:\n\n```{fence}\n{}```\n", source);
        }
    }
    out.push_str("## Mistakes `atomic check` refuses\n\n");
    for m in MISTAKES {
        let shown = if m.wrong.frontmatter.is_empty() && m.wrong.config == "{}" {
            m.wrong.body.to_owned()
        } else if m.wrong.frontmatter.is_empty() {
            format!("export const config = {};", m.wrong.config)
        } else {
            m.wrong.frontmatter.to_owned()
        };
        let _ = writeln!(
            out,
            "- {}, as in `{}`. `atomic check` reports \"{}\". {}",
            m.title, shown, m.says, m.fix
        );
    }
    out
}

