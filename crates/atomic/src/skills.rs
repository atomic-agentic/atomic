//! The authoring skills `atomic setup` installs for coding agents.
//!
//! A skill is an Agent Skills folder: a hand-written `SKILL.md` with only the
//! standard `name` and `description` fields, and a `references/` folder that
//! this module generates from the definitions the binary checks atoms with:
//! the configuration fields the loader accepts and refuses, the typed
//! `AtomConfig` declaration the compiler checks configuration against, the
//! generation profile an output schema must lower to, the model tiers and the
//! project layout defaults. A skill installed by a binary therefore describes
//! exactly that binary. The repository keeps a copy under `skills/`, and a
//! test fails when the copy and the binary disagree.
//!
//! The prompt syntax and CEL references are curated examples rather than
//! lists read from a table; tests compile every example through the real
//! compiler and expression checker, so they fail when the language moves.

use atomic_schema::lower::Profile;
use serde_json::Value;
use std::fmt::Write as _;

/// The one skill of the first pack.
pub const CREATE_ATOM: &str = "atomic-create-atom";

/// The hand-written instructions of [`CREATE_ATOM`].
const CREATE_ATOM_SKILL: &str = include_str!("../../../skills/atomic-create-atom/SKILL.md");

/// The first line of every generated reference.
const GENERATED: &str = "<!-- Generated by atomic from the definitions it checks atoms with. \
                         Do not edit: `atomic setup` rewrites this file. -->";

/// One file of the pack, by its path below the skills directory.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SkillFile {
    /// Relative path, `/`-separated, starting with the skill's name.
    pub path: String,
    /// The file's text.
    pub contents: String,
}

/// What the references are generated from. [`Definitions::binary`] is what
/// this build checks atoms with; tests substitute other values.
#[derive(Clone, Copy, Debug)]
pub struct Definitions<'a> {
    /// Configuration fields the loader reads.
    pub fields: &'a [&'a str],
    /// Configuration fields the loader refuses by name until a later version.
    pub later: &'a [&'a str],
    /// Atom kinds this version runs.
    pub kinds: &'a [&'a str],
    /// Model tiers a project maps to models.
    pub model_tiers: &'a [&'a str],
    /// The `authoring.d.ts` declaration of `AtomConfig`.
    pub declarations: &'a str,
    /// The manifest format version.
    pub format_version: u64,
    /// Default collection globs.
    pub collections: &'a [(&'a str, &'a [&'a str])],
    /// The generation profile output schemas lower to.
    pub profile: &'a Profile,
}

impl Definitions<'static> {
    /// The definitions this binary checks atoms with.
    pub fn binary() -> Self {
        use atomic_core::{atom, project, typed};
        Self {
            fields: atom::FIELDS,
            later: atom::LATER,
            kinds: atom::KINDS,
            model_tiers: typed::MODEL_TIERS,
            declarations: atom::AUTHORING_DECLARATIONS,
            format_version: project::FORMAT_VERSION,
            collections: project::DEFAULT_COLLECTIONS,
            profile: &atomic_schema::lower::OPENAI_STRICT,
        }
    }
}

/// The pack this binary installs.
pub fn pack() -> Result<Vec<SkillFile>, String> {
    pack_from(&Definitions::binary())
}

/// The pack generated from `defs`.
pub fn pack_from(defs: &Definitions<'_>) -> Result<Vec<SkillFile>, String> {
    let file = |name: &str, contents: String| SkillFile {
        path: format!("{CREATE_ATOM}/{name}"),
        contents,
    };
    Ok(vec![
        file("SKILL.md", CREATE_ATOM_SKILL.to_owned()),
        file("references/fields.md", fields_reference(defs)?),
        file("references/prompt-syntax.md", prompt_reference()),
        file("references/cel.md", cel_reference()),
        file(
            "references/strict-schemas.md",
            strict_reference(defs.profile),
        ),
    ])
}

/// One member of the `AtomConfig` interface.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Member {
    /// The field.
    pub name: String,
    /// Its TypeScript type, as declared.
    pub ty: String,
    /// The declaration's doc comment, if any.
    pub doc: Option<String>,
}

/// Read the members of `interface AtomConfig` from `authoring.d.ts`. A line
/// the reader does not understand is an error, so a change in the
/// declaration's shape fails generation instead of being skipped.
pub fn config_members(declarations: &str) -> Result<Vec<Member>, String> {
    let mut lines = declarations
        .lines()
        .skip_while(|line| !line.starts_with("export interface AtomConfig<"));
    if lines.next().is_none() {
        return Err("authoring.d.ts declares no `AtomConfig` interface".into());
    }
    let mut members = Vec::new();
    let mut doc = None;
    for line in lines {
        let line = line.trim();
        if line == "}" {
            return Ok(members);
        }
        if let Some(comment) = line.strip_prefix("/**") {
            let comment = comment
                .strip_suffix("*/")
                .ok_or_else(|| format!("AtomConfig: multi-line comment `{line}`"))?;
            doc = Some(comment.trim().to_owned());
            continue;
        }
        let (name, ty) = line
            .split_once(':')
            .ok_or_else(|| format!("AtomConfig: cannot read `{line}`"))?;
        let name = name.trim_end_matches('?');
        let ty = ty
            .trim()
            .strip_suffix(';')
            .ok_or_else(|| format!("AtomConfig: `{line}` does not end its type with `;`"))?;
        if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            return Err(format!("AtomConfig: cannot read `{line}`"));
        }
        members.push(Member {
            name: name.to_owned(),
            ty: ty.trim().to_owned(),
            doc: doc.take(),
        });
    }
    Err("AtomConfig: the interface does not end".into())
}

