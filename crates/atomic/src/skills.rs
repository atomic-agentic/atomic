/// The eval case and CEL reference.
pub fn cel_reference() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{GENERATED}\n");
    out.push_str(
        "# Eval cases and CEL assertions\n\n\
         An eval case is an input and a list of assertions about the output. For atom \
         `<name>`, each `.yaml` file in `evals/<name>/` is one case, named by its file:\n\n\
         ```yaml\n\
         input:\n  text: Export crashes when the file name contains an accented character.\n\
         expect:\n  - \"output.category == 'bug'\"\n  - \"output.summary.size() > 0\"\n\
         ```\n\n\
         `input` must match the input schema. `expect` is a nonempty list of CEL \
         expressions over `input` and `output`; every one must be true. Quote each \
         expression. There is no `output`, `atom` or `atomic` key in a case. For many \
         cases, a `.jsonl` file holds one `{\"input\": …, \"expect\": […]}` object per \
         line.\n\n\
         Field paths are resolved against the atom's schemas, so a misspelt field is an \
         error rather than a false assertion. Assert behaviour the task needs, not the \
         exact wording of a model's answer.\n\n\
         ## CEL cheat sheet\n\n\
         Each expression below is true for an output \
         `{category: 'bug', summary: 'Export crashes on accented file names.', \
         labels: ['export', 'crash'], priority: 2}`.\n\n",
    );
    for (expr, meaning) in CEL_EXAMPLES {
        let _ = writeln!(out, "- {meaning}: `{expr}`");
    }
    out.push_str(
        "\nCEL is not JavaScript: strings use `size()`, not `.length`; lists use \
         `exists`, `all`, `filter` and `map` with a variable name as the first argument; \
         `has(output.field)` tests an optional field; strings are single- or \
         double-quoted; `==` compares values and there is no `===`.\n",
    );
    out
}

/// The strict output schema reference.
pub fn strict_reference(profile: &Profile) -> String {
    let list = |values: &[&str]| {
        values
            .iter()
            .map(|v| format!("`{v}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut out = String::new();
    let _ = writeln!(out, "{GENERATED}\n");
    let _ = write!(
        out,
        "# Output schema rules\n\n\
         The output schema of a `lite` or `codex` atom constrains the model's decoding, so \
         it must lower to the generation profile `{name}`. `atomic check` refuses a schema \
         that cannot be lowered and names the schema path that fails. Input schemas and \
         `exec` outputs are not lowered: any JSON Schema 2020-12 that resolves offline \
         works there.\n\n\
         The full schema is still the contract: atomic validates every answer against all \
         of it, including the keywords the profile cannot express.\n\n\
         ## Rules\n\n\
         - The root is an object schema (`type: object`), not a list or an `anyOf`.\n\
         - Give every object `additionalProperties: false` and list its fields under \
         `properties`. Lowering makes every property required; a property your schema \
         leaves optional becomes nullable for the model, and atomic turns its `null` \
         back into an omitted field.\n\
         - Do not also allow `null` for an optional property: the model could not say \
         \"omitted\" there, so its `null` is kept as a value.\n\
         - Alternatives (`anyOf`) that disagree about what `null` means need a required \
         `const` or `enum` property that tells them apart.\n\
         - These keywords make a schema impossible to lower, and `atomic check` fails: \
         {refused}. Use `anyOf` with a `const` discriminator, or `enum`, instead.\n\n\
         ## What the model sees\n\n\
         - Kept everywhere: {kept}.\n\
         - Kept on strings: {string}; `format` only as {formats}.\n\
         - Kept on numbers and integers: {number}.\n\
         - Kept on arrays: {array}.\n\
         - Any other keyword, such as `maxLength` or `uniqueItems`, is removed from the \
         generation schema and stated in the field's description instead. atomic still \
         enforces it on the answer.\n\n\
         ## Advice\n\n\
         - Bound every string with `maxLength` and every list with `maxItems`.\n\
         - Prefer `enum` for categories, and `integer` with `minimum` and `maximum` for \
         scores.\n\
         - Keep schemas in YAML sidecars beside the atom; reuse shared definitions with \
         a relative `$ref`. Remote references are never fetched.\n",
        name = profile.name,
        refused = list(profile.refused),
        kept = list(profile.kept),
        string = list(profile.string),
        formats = list(profile.formats),
        number = list(profile.number),
        array = list(profile.array),
    );
    out
}

/// The Agent Skills specification's limits.
const MAX_NAME: usize = 64;
const MAX_DESCRIPTION: usize = 1024;
const MAX_COMPATIBILITY: usize = 500;
const ALLOWED_FRONTMATTER: &[&str] = &[
    "name",
    "description",
    "license",
    "allowed-tools",
    "metadata",
    "compatibility",
];

/// Check one skill against the Agent Skills specification: its `SKILL.md`
/// frontmatter has a valid `name` equal to `dir_name`, a description within
/// the limit, and no fields the specification does not define. Returns every
/// problem found.
pub fn validate_skill(dir_name: &str, skill_md: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let Some(rest) = skill_md.strip_prefix("---\n") else {
        return vec!["SKILL.md must start with `---` frontmatter".into()];
    };
    let Some((frontmatter, _body)) = rest.split_once("\n---\n") else {
        return vec!["SKILL.md frontmatter is not closed by `---`".into()];
    };
    let doc = match atomic_schema::yaml::load(std::path::Path::new("SKILL.md"), frontmatter) {
        Ok(doc) => doc.value,
        Err(e) => return vec![format!("frontmatter: {e}")],
    };
    let Some(fields) = doc.as_object() else {
        return vec!["frontmatter must be a mapping".into()];
    };
    for key in fields.keys() {
        if !ALLOWED_FRONTMATTER.contains(&key.as_str()) {
            problems.push(format!("unexpected frontmatter field `{key}`"));
        }
    }
    match fields.get("name").and_then(Value::as_str).map(str::trim) {
        None | Some("") => problems.push("`name` must be a nonempty string".into()),
        Some(name) => {
            if name.chars().count() > MAX_NAME {
                problems.push(format!("`name` is longer than {MAX_NAME} characters"));
            }
            if name.to_lowercase() != name {
                problems.push("`name` must be lowercase".into());
            }
            if name.starts_with('-') || name.ends_with('-') {
                problems.push("`name` cannot start or end with a hyphen".into());
            }
            if name.contains("--") {
                problems.push("`name` cannot contain consecutive hyphens".into());
            }
            if !name.chars().all(|c| c.is_alphanumeric() || c == '-') {
                problems.push("`name` may hold only letters, digits and hyphens".into());
            }
            if name != dir_name {
                problems.push(format!(
                    "`name` {name} does not match its directory {dir_name}"
                ));
            }
        }
    }
    match fields.get("description").and_then(Value::as_str) {
        None => problems.push("`description` must be a nonempty string".into()),
        Some(d) if d.trim().is_empty() => {
            problems.push("`description` must be a nonempty string".into());
        }
        Some(d) if d.chars().count() > MAX_DESCRIPTION => problems.push(format!(
            "`description` is longer than {MAX_DESCRIPTION} characters"
        )),
        Some(_) => {}
    }
    if let Some(c) = fields.get("compatibility") {
        match c.as_str() {
            Some(c) if c.chars().count() <= MAX_COMPATIBILITY => {}
            _ => problems.push(format!(
                "`compatibility` must be a string of at most {MAX_COMPATIBILITY} characters"
            )),
        }
    }
    problems
}

