#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Keep the workspace in step with the Codex revision in deps/codex.toml.
#
#   scripts/codex-pin.sh check   # fail if anything below has drifted (CI runs this)
#   scripts/codex-pin.sh write   # regenerate the patch block in Cargo.toml
#
# It checks three things against codex-rs/ at the pinned revision:
#
# 1. The [patch...] sections of Cargo.toml are copied byte for byte from Codex's
#    codex-rs/Cargo.toml, between the BEGIN and END markers. atomic adds one entry inside
#    [patch.crates-io], marked as atomic's: sqlx-postgres from the same sqlx fork revision
#    Codex uses for sqlx-core, because Codex patches only sqlx-core and sqlx-sqlite and a
#    crates.io sqlx-postgres does not build against the patched core.
# 2. rust-toolchain.toml names the toolchain Codex's rust-toolchain.toml names.
# 3. deps/codex.toml records that same toolchain.
#
# Codex's files are read from CODEX_SRC (a local clone of openai/codex) when set, otherwise
# downloaded from GitHub at the pinned revision.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIN="${ROOT}/deps/codex.toml"
MANIFEST="${ROOT}/Cargo.toml"
BEGIN="# BEGIN codex patch block: generated by scripts/codex-pin.sh from deps/codex.toml. Do not edit."
END="# END codex patch block"

pin_value() {
    sed -n "s/^$1 = \"\\(.*\\)\"\$/\\1/p" "${PIN}" | head -n1
}

REV="$(pin_value rev)"
TOOLCHAIN_PIN="$(pin_value toolchain)"
if [ -z "${REV}" ] || [ -z "${TOOLCHAIN_PIN}" ]; then
    echo "scripts/codex-pin.sh: deps/codex.toml must set rev and toolchain" >&2
    exit 2
fi

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

fetch() { # codex-rs relative path, destination
    if [ -n "${CODEX_SRC:-}" ]; then
        git -C "${CODEX_SRC}" show "${REV}:codex-rs/$1" >"$2"
    else
        curl -fsSL --retry 3 -o "$2" "https://raw.githubusercontent.com/openai/codex/${REV}/codex-rs/$1"
    fi
}

fetch Cargo.toml "${WORK}/codex-Cargo.toml"
fetch rust-toolchain.toml "${WORK}/codex-toolchain.toml"

# Every [patch...] section of Codex's manifest, verbatim, with trailing blank lines dropped
# from each section and atomic's sqlx-postgres entry appended to [patch.crates-io].
generate_block() {
    awk -v begin="${BEGIN}" -v end="${END}" '
        function flush(   i) {
            if (header == "") return
            while (n > 0 && body[n] ~ /^[ \t]*$/) n--
            if (printed) print ""
            print header
            for (i = 1; i <= n; i++) print body[i]
            if (header == "[patch.crates-io]") {
                if (sqlx_core == "") { print "codex [patch.crates-io] has no sqlx-core entry" > "/dev/stderr"; exit 3 }
                print "# atomic: the Postgres driver from the same sqlx fork revision as sqlx-core."
                print sqlx_core
            }
            printed = 1
            header = ""; n = 0
        }
        BEGIN { print begin }
        /^\[/ {
            flush()
            if ($0 ~ /^\[patch[.]/) { header = $0; n = 0 }
            next
        }
        header != "" {
            body[++n] = $0
            if ($0 ~ /^sqlx-core = /) { sqlx_core = $0; sub(/^sqlx-core/, "sqlx-postgres", sqlx_core) }
        }
        END { flush(); print end }
    ' "${WORK}/codex-Cargo.toml"
}

generate_block >"${WORK}/expected"

current_block() {
    awk -v begin="${BEGIN}" -v end="${END}" '
        $0 == begin { inside = 1 }
        inside { print }
        $0 == end { inside = 0 }
    ' "${MANIFEST}"
}

codex_toolchain="$(sed -n 's/^channel = "\(.*\)"$/\1/p' "${WORK}/codex-toolchain.toml")"
our_toolchain="$(sed -n 's/^channel = "\(.*\)"$/\1/p' "${ROOT}/rust-toolchain.toml")"

case "${1:-}" in
    write)
        if grep -qxF "${BEGIN}" "${MANIFEST}"; then
            awk -v begin="${BEGIN}" -v end="${END}" -v block="${WORK}/expected" '
                $0 == begin { while ((getline line < block) > 0) print line; skip = 1; next }
                skip && $0 == end { skip = 0; next }
                !skip { print }
            ' "${MANIFEST}" >"${WORK}/manifest"
        else
            { cat "${MANIFEST}"; echo; cat "${WORK}/expected"; } >"${WORK}/manifest"
        fi
        cp "${WORK}/manifest" "${MANIFEST}"
        echo "Cargo.toml: patch block written from Codex ${REV}"
        ;;
    check)
        status=0
        if ! current_block | diff -u --label "Cargo.toml (committed)" --label "codex ${REV} (expected)" - "${WORK}/expected"; then
            echo "scripts/codex-pin.sh: the patch block in Cargo.toml differs from Codex ${REV}; run scripts/codex-pin.sh write" >&2
            status=1
        fi
        if [ "${our_toolchain}" != "${codex_toolchain}" ]; then
            echo "scripts/codex-pin.sh: rust-toolchain.toml has ${our_toolchain}, Codex ${REV} has ${codex_toolchain}" >&2
            status=1
        fi
        if [ "${TOOLCHAIN_PIN}" != "${codex_toolchain}" ]; then
            echo "scripts/codex-pin.sh: deps/codex.toml records toolchain ${TOOLCHAIN_PIN}, Codex ${REV} has ${codex_toolchain}" >&2
            status=1
        fi
        [ "${status}" -eq 0 ] && echo "Codex pin ${REV}: patch block and toolchain match"
        exit "${status}"
        ;;
    *)
        echo "usage: scripts/codex-pin.sh check|write" >&2
        exit 2
        ;;
esac
